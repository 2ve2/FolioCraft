"""Build Ichnara brand assets (v1.3) from reviewed vector masters; no provider operations."""
from pathlib import Path
import copy,json,subprocess,xml.etree.ElementTree as ET

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'apps/web/public/brand/ichnara'
REVIEW=ROOT/'docs/brand/review-round-2'
V13=ROOT/'docs/brand/v1.3'
INK,ACCENT='#241B38','#3F46C8'
NS='http://www.w3.org/2000/svg'
ET.register_namespace('',NS)

def children(element):
    """Serialize fixed artwork children without changing its paths or transforms."""
    return ''.join(ET.tostring(child,encoding='unicode') for child in element)

def document(body,box,color,label):
    """Wrap proportional, accessible fixed artwork in a standalone vector master."""
    return f'<svg xmlns="{NS}" viewBox="{box}" fill="{color}" role="img" aria-label="{label}">{body}</svg>'

latin=ET.parse(REVIEW/'i-01-capped.svg').getroot()
# v1.3: Noto Sans Arabic 600 outlines sized to the emblem like the Latin capital (docs/brand/v1.3/generate.py).
arabic=ET.parse(V13/'ar-sans-600.svg').getroot()
arabic_box=arabic.get('viewBox')
arabic_word_box=arabic.get('data-word-box')
emblem=children(ET.parse(OUT/'ichnara-emblem-ink.svg').getroot())
latin_word=children(latin)
latin_lock=f'<g transform="translate(0 10) scale(2.4)">{emblem}</g><g transform="translate(690 0)">{latin_word}</g>'
arabic_lock=children(arabic)
# Two-colour lockups: indigo emblem, ink word. The single-colour files remain for one-ink uses.
def duo(lock,emblem_first):
    groups=ET.fromstring(f'<svg xmlns="{NS}">{lock}</svg>')
    for index,group in enumerate(groups):
        group.set('fill',ACCENT if (index==0)==emblem_first else INK)
    return children(groups)
(OUT/'ichnara-logo-duo.svg').write_text(document(duo(latin_lock,True),'-40 -34 3241 681',INK,'Ichnara'))
(OUT/'ichnara-logo-ar-duo.svg').write_text(document(duo(arabic_lock,False),arabic_box,INK,'إيكنارا — Ichnara'))
for name,color in [('ink',INK),('violet',ACCENT),('white','#FFFFFF')]:
    (OUT/f'ichnara-wordmark-{name}.svg').write_text(document(latin_word,latin.get('viewBox'),color,'Ichnara'))
    (OUT/f'ichnara-initial-{name}.svg').write_text(document(ET.tostring(latin[0],encoding='unicode'),'-40 -34 194 681',color,'Ichnara initial'))
    (OUT/f'ichnara-logo-{name}.svg').write_text(document(latin_lock,'-40 -34 3241 681',color,'Ichnara'))
    (OUT/f'ichnara-emblem-{name}.svg').write_text(document(emblem,'0 0 235 240',color,'Ichnara emblem'))
    (OUT/f'ichnara-logo-ar-{name}.svg').write_text(document(arabic_lock,arabic_box,color,'إيكنارا — Ichnara'))
    (OUT/f'ichnara-wordmark-ar-{name}.svg').write_text(document(ET.tostring(arabic[0],encoding='unicode'),arabic_word_box,color,'إيكنارا — Ichnara'))
icon=(OUT/'favicon.svg').read_text().replace('#6E46D6','#3F46C8')
(OUT/'favicon.svg').write_text(icon)
(ROOT/'apps/web/src/app/icon.svg').write_text(icon)

# Export the same geometry as typed data for inherited header/footer color and locale rendering.
# Display size: the Latin capital and the tallest Arabic letter render at the same height (31.5px at
# the 170px Latin width). `trim` pulls in the Arabic descender space so both lockups occupy the same row.
LATIN_SCALE=170/3241
def display(box,baseline,cap_height):
    x,y,w,h=map(float,box.split());scale=LATIN_SCALE*600/cap_height
    below=(y+h-baseline)*scale;latin_below=(647-600)*LATIN_SCALE
    return {'width':round(w*scale,1),'height':round(h*scale,1),'trim':round(max(0,below-latin_below),1)}
arabic_baseline=float(arabic[0].get('transform').rstrip(')').split()[-1])
artwork={}
for locale,body,box,size in [('en',latin_lock,'-40 -34 3241 681',display('-40 -34 3241 681',600,600)),
                              ('ar',arabic_lock,arabic_box,display(arabic_box,arabic_baseline,238*0.98))]:
    root=ET.fromstring(document(body,box,'currentColor','Ichnara'))
    groups=list(root);emblem_index=0 if locale=='en' else 1
    artwork[locale]={'viewBox':box,**size,'groups':[{'role':'emblem' if index==emblem_index else 'word','transform':group.get('transform',''),'paths':[dict(path.attrib) for path in group]} for index,group in enumerate(groups)]}
(ROOT/'apps/web/src/components/ui/brand-artwork.ts').write_text('/** Ichnara v1.3 outlined artwork; generated by scripts/build-brand-kit.py. */\nexport const brandArtwork = '+json.dumps(artwork,ensure_ascii=False,indent='\t')+' as const;\n')

board=(REVIEW/'brand-overview-spacing.svg').read_text().replace('#6E46D6','#3F46C8').replace('V1.1','V1.3').replace('y="493"','y="514"').replace('M0 34L88 0V600H0Z',latin[0].get('d'))
board=board.replace('height="1000"','height="1400"').replace('viewBox="0 0 1600 1000"','viewBox="0 0 1600 1400"')
board=board.replace('</svg>',f'<rect y="1000" width="1600" height="320" fill="#F8F6FC"/><text x="80" y="1050" fill="#796A91" font-family="Arial" font-size="18">ARABIC / NOTO SANS ARABIC 600 OUTLINES (V1.3)</text><g fill="#3F46C8" transform="translate(150 1070) scale(.80)">{arabic_lock}</g></svg>')
(OUT/'brand-overview.svg').write_text(board)
manifest={'brand':'Ichnara','arabicName':'إيكنارا','version':'1.3','primary':'ichnara-logo-duo.svg','arabicDuo':'ichnara-logo-ar-duo.svg','mono':'ichnara-logo-ink.svg','reverse':'ichnara-logo-white.svg','accent':'ichnara-logo-violet.svg','arabicPrimary':'ichnara-logo-ar-ink.svg','arabicReverse':'ichnara-logo-ar-white.svg','arabicAccent':'ichnara-logo-ar-violet.svg','emblem':'ichnara-emblem-violet.svg','favicon':'favicon.svg','wordmark':'ichnara-wordmark-ink.svg','colors':{'accent':'#3F46C8','ink':'#241B38','white':'#FFFFFF'},'construction':'Drawn Latin I1 wordmark; Arabic derived from Noto Sans Arabic 600 under SIL OFL, sized to the emblem; preserved folded-band emblem; two-colour primary (indigo emblem, ink word)','humanApproved':'2026-10-18: I1/A1/C1 and Arabic spelling; 2026-10-23: the human asked for a review of logo weight and colour and delegated the decision (v1.3)'}
(OUT/'brand.json').write_text(json.dumps(manifest,ensure_ascii=False,indent='\t')+'\n')
(OUT/'NotoSansArabic-LICENSE.txt').write_bytes((REVIEW/'NotoSansArabic-LICENSE.txt').read_bytes())
print('Built approved vector masters, manifest and shared locale artwork data.')
